/**
 * Regenerates src/ryb-hue-table.js from rybitten (a dev dependency only, so
 * the published package keeps zero runtime dependencies).
 *
 * For each whole RYB wheel angle 0..359 it takes rybitten's fully saturated
 * mid-lightness color on Itten's wheel and records that color's OKLCH hue.
 * Only the hue is kept: lightness and chroma stay under colorhorse's own
 * OKLCH control, so the RYB wheel changes WHERE hues sit around the ring,
 * not how light or saturated they are.
 *
 *   node scripts/build-ryb-hue-table.js
 */
import { writeFileSync } from "node:fs";
import { rybHsl2rgb } from "rybitten";
import { srgbToOklch } from "../src/oklch.js";

const hues = [];
for (let angle = 0; angle < 360; angle++) {
	const [r, g, b] = rybHsl2rgb([angle, 1, 0.5]);
	let { H } = srgbToOklch(r * 255, g * 255, b * 255);
	// Unwrap so the table is strictly increasing (runtime lookups rely on it).
	while (hues.length && H <= hues[hues.length - 1]) H += 360;
	hues.push(Number(H.toFixed(3)));
}
if (hues[hues.length - 1] >= hues[0] + 360) {
	throw new Error("RYB -> OKLCH hue mapping is not monotonic; the table can't be inverted.");
}

const rows = [];
for (let i = 0; i < hues.length; i += 12) rows.push(`\t${hues.slice(i, i + 12).join(", ")},`);

writeFileSync(
	new URL("../src/ryb-hue-table.js", import.meta.url),
	`// Generated by scripts/build-ryb-hue-table.js from rybitten (Itten wheel) -- do not edit.
// RYB_HUE_TABLE[a] is the OKLCH hue at RYB wheel angle a (degrees, unwrapped
// so the list is strictly increasing).
export const RYB_HUE_TABLE = [
${rows.join("\n")}
];
`,
);
